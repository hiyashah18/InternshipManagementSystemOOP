    public WebServer(UserService users, CompanyService companies,
                     InternshipService internships, ApplicationService applications) {
        this.users = users;
        this.companies = companies;
        this.internships = internships;
        this.applications = applications;
    }

    public void start(int port) throws IOException {
        HttpServer server = HttpServer.create(new InetSocketAddress(port), 0);
        server.createContext("/", this);
        server.setExecutor(null);                       // single-threaded
        server.start();
        System.out.println("Internship Management System is running.");
        System.out.println("Open this address in your browser:  http://localhost:" + port);
        System.out.println("Press Ctrl+C to stop the server.");
    }

    // ------------------------------------------------------------------ request handling

    /** Holds everything we need to know about one incoming request. */
    private class Request {
        final HttpExchange ex;
        final String method;
        final String path;
        final Map<String, String> params = new HashMap<String, String>();   // query + form fields
        final User user;

        Request(HttpExchange ex) throws IOException {
            this.ex = ex;
            this.method = ex.getRequestMethod();
            this.path = ex.getRequestURI().getPath();
            parse(ex.getRequestURI().getRawQuery());
            if ("POST".equals(method)) {
                parse(readBody(ex.getRequestBody()));
            }
            this.user = currentUser(ex);
        }

        boolean isPost() { return "POST".equals(method); }

        String get(String key) {
            String v = params.get(key);
            return v == null ? "" : v;
        }

        private void parse(String data) {
            if (data == null || data.isEmpty()) {
                return;
            }
            for (String pair : data.split("&")) {
                int i = pair.indexOf('=');
                String k = i < 0 ? pair : pair.substring(0, i);
                String v = i < 0 ? "" : pair.substring(i + 1);
                params.put(decode(k), decode(v));
            }
        }
    }

    @Override
    public void handle(HttpExchange ex) throws IOException {
        try {
            route(new Request(ex));
        } catch (Exception e) {
            e.printStackTrace();
            respond(ex, 500, Html.page("Error", null, null, null,
                    "<div class='card'><h2>Something went wrong</h2><p>" + Html.esc(String.valueOf(e.getMessage()))
                    + "</p><a class='btn' href='/'>Back to home</a></div>"));
        } finally {
            ex.close();
        }
    }

    private void route(Request r) throws IOException {
        String p = r.path;

        // pages that do not need a login
        if (p.equals("/")) {
            redirect(r.ex, r.user == null ? "/login" : "/dashboard", null);
            return;
        }
        if (p.equals("/login")) {
            if (r.isPost()) doLogin(r); else showLogin(r);
            return;
        }
        if (p.equals("/register")) {
            if (r.isPost()) doRegister(r); else showRegister(r);
            return;
        }
        if (p.equals("/logout")) {
            doLogout(r);
            return;
        }

        // everything below needs a logged-in user
        if (r.user == null) {
            redirect(r.ex, "/login?err=" + enc("Please log in first."), null);
            return;
        }

        switch (p) {
            case "/dashboard":
                showDashboard(r);
                break;

            // ---- student pages
            case "/internships":
                if (allow(r, "STUDENT", false)) showInternships(r);
                break;
            case "/apply":
                if (allow(r, "STUDENT", true)) doApply(r);
                break;
            case "/applications":
                if (allow(r, "STUDENT", false)) showApplications(r);
                break;

            // ---- company pages
            case "/company/internships":
                if (allow(r, "COMPANY", false)) showCompanyInternships(r);
                break;
            case "/company/post":
                if (allow(r, "COMPANY", false)) showPostForm(r);
                break;
            case "/company/create":
                if (allow(r, "COMPANY", true)) doCreateInternship(r);
                break;
            case "/company/close":
                if (allow(r, "COMPANY", true)) doCloseInternship(r);
                break;
            case "/company/applicants":
                if (allow(r, "COMPANY", false)) showApplicants(r);
                break;
            case "/company/decide":
                if (allow(r, "COMPANY", true)) doDecide(r);
                break;

            // ---- administrator pages
            case "/admin":
                if (allow(r, "ADMIN", false)) showAdmin(r);
                break;
            case "/admin/remove-student":
                if (allow(r, "ADMIN", true)) doRemoveStudent(r);
                break;
            case "/admin/remove-internship":
                if (allow(r, "ADMIN", true)) doRemoveInternship(r);
                break;

            default:
                respond(r.ex, 404, Html.page("Not found", r.user, null, null,
                        "<div class='card'><h2>Page not found</h2>"
                        + "<a class='btn' href='/dashboard'>Go to dashboard</a></div>"));
        }
    }

    /** Checks the role (and POST when needed). If not allowed, redirects and returns false. */
    private boolean allow(Request r, String role, boolean needPost) throws IOException {
        if (!role.equals(r.user.getRole())) {
            redirect(r.ex, "/dashboard?err=" + enc("You do not have access to that page."), null);
            return false;
        }
        if (needPost && !r.isPost()) {
            redirect(r.ex, "/dashboard", null);
            return false;
        }
        return true;
    }

