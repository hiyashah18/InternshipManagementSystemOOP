    private void doCreateInternship(Request r) throws IOException {
        try {
            Company c = companies.findById(companyIdOf(r));
            int stipend = Validator.parseInt(r.get("stipend"), "Stipend");
            int months = Validator.parseInt(r.get("months"), "Duration");
            internships.post(c, r.get("title"), r.get("location"), r.get("description"), stipend, months);
            redirect(r.ex, "/company/internships?msg=" + enc("Internship posted successfully."), null);
        } catch (InternshipSystemException e) {
            redirect(r.ex, "/company/post?err=" + enc(e.getMessage()), null);
        }
    }

    private void doCloseInternship(Request r) throws IOException {
        try {
            internships.close(r.get("internshipId"), companyIdOf(r));
            redirect(r.ex, "/company/internships?msg=" + enc("Internship closed."), null);
        } catch (InternshipSystemException e) {
            redirect(r.ex, "/company/internships?err=" + enc(e.getMessage()), null);
        }
    }

    private void showApplicants(Request r) throws IOException {
        Internship i = internships.findById(r.get("internshipId"));
        if (i == null || !i.getCompanyId().equals(companyIdOf(r))) {
            redirect(r.ex, "/company/internships?err=" + enc("Internship not found."), null);
            return;
        }
        StringBuilder b = new StringBuilder("<h1>Applicants</h1><p class='muted'>")
            .append(Html.esc(i.getTitle())).append(" &middot; ").append(Html.esc(i.getLocation())).append("</p>");
        List<Application> apps = applications.getByInternship(i.getId());
        if (apps.isEmpty()) {
            b.append("<div class='card'>No applications received yet.</div>");
        } else {
            b.append("<table><tr><th>Student</th><th>Course</th><th>Skills</th><th>Applied on</th><th>Status</th><th>Decision</th></tr>");
            for (Application a : apps) {
                User s = users.findById(a.getStudentId());
                String course = "";
                String skills = "";
                if (s instanceof Student) {
                    course = ((Student) s).getCourse();
                    skills = ((Student) s).getSkills();
                }
                b.append("<tr><td>").append(s == null ? "(removed)" : Html.esc(s.getName()) + "<br><span class='muted'>"
                        + Html.esc(s.getEmail()) + "</span>")
                 .append("</td><td>").append(Html.esc(course)).append("</td><td>").append(Html.esc(skills))
                 .append("</td><td>").append(a.getAppliedOn()).append("</td><td>").append(Html.badge(a.getStatus()))
                 .append("</td><td>")
                 .append(decisionForm(a, i, "ACCEPTED", "Accept", "green"))
                 .append(decisionForm(a, i, "REJECTED", "Reject", "red"))
                 .append("</td></tr>");
            }
            b.append("</table>");
        }
        b.append("<p><a class='btn grey' href='/company/internships'>Back</a></p>");
        respond(r.ex, 200, Html.page("Applicants", r.user, r.get("msg"), r.get("err"), b.toString()));
    }

    private String decisionForm(Application a, Internship i, String status, String label, String css) {
        return "<form class='inline' method='post' action='/company/decide'>"
             + "<input type='hidden' name='applicationId' value='" + Html.esc(a.getId()) + "'>"
             + "<input type='hidden' name='internshipId' value='" + Html.esc(i.getId()) + "'>"
             + "<input type='hidden' name='status' value='" + status + "'>"
             + "<button type='submit' class='" + css + "'>" + label + "</button></form> ";
    }

    private void doDecide(Request r) throws IOException {
        String back = "/company/applicants?internshipId=" + enc(r.get("internshipId"));
        try {
            ApplicationStatus status = ApplicationStatus.fromText(r.get("status"));
            applications.updateStatus(r.get("applicationId"), status, companyIdOf(r));
            redirect(r.ex, back + "&msg=" + enc("Application marked as " + status + "."), null);
        } catch (InternshipSystemException e) {
            redirect(r.ex, back + "&err=" + enc(e.getMessage()), null);
        }
    }

