    private void doRegister(Request r) throws IOException {
        try {
            String email = r.get("email");
            Validator.requireText(r.get("name"), "Name");
            Validator.requirePassword(r.get("password"));
            users.ensureEmailFree(email);
            if ("company".equals(r.get("role"))) {
                Validator.requireText(r.get("companyName"), "Company name");
                Validator.requireText(r.get("industry"), "Industry");
                Validator.requireText(r.get("location"), "Company location");
                Company c = companies.addCompany(r.get("companyName"), r.get("industry"), r.get("location"));
                users.registerCompanyRep(r.get("name"), email, r.get("password"), c.getId());
            } else {
                users.registerStudent(r.get("name"), email, r.get("password"), r.get("course"), r.get("skills"));
            }
            redirect(r.ex, "/login?msg=" + enc("Registration successful. Please log in."), null);
        } catch (InternshipSystemException e) {
            redirect(r.ex, "/register?err=" + enc(e.getMessage()), null);
        }
    }

    // ------------------------------------------------------------------ dashboard

    private void showDashboard(Request r) throws IOException {
        User u = r.user;
        StringBuilder b = new StringBuilder();
        b.append("<h1>Welcome, ").append(Html.esc(u.getName())).append("</h1>");
        b.append("<p class='muted'>").append(Html.esc(u.describe())).append("</p><div class='grid'>");

        if (u instanceof Student) {
            List<Application> mine = applications.getByStudent(u.getId());
            b.append(Html.stat("Open internships", internships.search("").size()));
            b.append(Html.stat("My applications", mine.size()));
            b.append(Html.stat("Pending", applications.countByStatus(mine, ApplicationStatus.PENDING)));
            b.append(Html.stat("Accepted", applications.countByStatus(mine, ApplicationStatus.ACCEPTED)));
            b.append(Html.stat("Rejected", applications.countByStatus(mine, ApplicationStatus.REJECTED)));
        } else if (u instanceof CompanyRepresentative) {
            List<Internship> posts = internships.getByCompany(((CompanyRepresentative) u).getCompanyId());
            int total = 0;
            int pending = 0;
            for (Internship i : posts) {
                List<Application> apps = applications.getByInternship(i.getId());
                total += apps.size();
                pending += applications.countByStatus(apps, ApplicationStatus.PENDING);
            }
            b.append(Html.stat("My internships", posts.size()));
            b.append(Html.stat("Total applicants", total));
            b.append(Html.stat("Pending review", pending));
        } else {
            b.append(Html.stat("Users", users.getAll().size()));
            b.append(Html.stat("Companies", companies.getAll().size()));
            b.append(Html.stat("Internships", internships.getAll().size()));
            b.append(Html.stat("Applications", applications.getAll().size()));
        }
        b.append("</div>");
        respond(r.ex, 200, Html.page("Dashboard", u, r.get("msg"), r.get("err"), b.toString()));
    }

