    private void doLogin(Request r) throws IOException {
        try {
            User u = users.login(r.get("email"), r.get("password"));
            String sid = UUID.randomUUID().toString();
            sessions.put(sid, u.getId());
            redirect(r.ex, "/dashboard", "sid=" + sid + "; Path=/; HttpOnly");
        } catch (AuthenticationException e) {
            redirect(r.ex, "/login?err=" + enc(e.getMessage()), null);
        }
    }

    private void doLogout(Request r) throws IOException {
        String sid = cookie(r.ex, "sid");
        if (sid != null) {
            sessions.remove(sid);
        }
        redirect(r.ex, "/login?msg=" + enc("You have been logged out."), "sid=; Path=/; Max-Age=0");
    }

